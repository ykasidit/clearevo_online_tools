#!/bin/sh
# Builds the WebAssembly BatRay loads and embeds it (base64) in public/batray/jkbms-wasm-bytes.js, so
# the page and the node tests load it the same way (no fetch, no MIME type, no extra cache rule).
# wasm.sha256 records the sources it came from: test/batray_jk_parity.test.js fails when the Rust
# changed without a rebuild.
set -e
cd "$(dirname "$0")"
cargo rustc --quiet --release --target wasm32-unknown-unknown --features wasm-abi --lib --crate-type cdylib
W=target/wasm32-unknown-unknown/release/jkbms.wasm
OUT=../../public/batray/jkbms-wasm-bytes.js
{
  echo "// BatRay by ClearEvo.com - the JK BMS parser (rust/jkbms) as WebAssembly, base64. Generated by"
  echo "// rust/jkbms/build_wasm.sh - do not edit."
  echo "// Copyright (C) 2026 Kasidit Yusuf"
  echo "//"
  echo "// This program is free software; you can redistribute it and/or modify it"
  echo "// under the terms of the GNU General Public License as published by the Free"
  echo "// Software Foundation; either version 2 of the License, or (at your option)"
  echo "// any later version."
  echo "//"
  echo "// This program is distributed in the hope that it will be useful, but WITHOUT"
  echo "// ANY WARRANTY; without even the implied warranty of MERCHANTABILITY or"
  echo "// FITNESS FOR A PARTICULAR PURPOSE. See the GNU General Public License for"
  echo "// more details: https://www.gnu.org/licenses/old-licenses/gpl-2.0.html"
  echo "// Source: https://github.com/ykasidit/clearevo_online_tools (rust/jkbms)"
  printf "export const WASM_B64 = '%s';\n" "$(base64 -w0 < $W)"
} > $OUT
cat Cargo.toml $(LC_ALL=C ls src/*.rs) | sha256sum | cut -d' ' -f1 > wasm.sha256
echo "$(wc -c < $W) bytes of wasm -> $OUT"
